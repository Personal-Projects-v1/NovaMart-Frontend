import type { Product, ProductBadge, ProductSpecGroup, ProductVariantGroup } from "@/types";

let seq = 0;
function nextId() {
  seq += 1;
  return `p-${seq.toString().padStart(3, "0")}`;
}

function img(seed: string, i: number) {
  return `https://picsum.photos/seed/${seed}-${i}/900/900`;
}

interface Seed {
  name: string;
  brandId: string;
  categoryId: string;
  price: number;
  compareAtPrice?: number;
  rating: number;
  reviewCount: number;
  stock: number;
  badges: ProductBadge[];
  shortDescription: string;
  description: string;
  variants: ProductVariantGroup[];
  specGroups: ProductSpecGroup[];
  tags: string[];
  daysAgo: number;
  warrantyMonths?: number;
  imgSeed: string;
}

function build(seed: Seed): Product {
  const id = nextId();
  const slug = seed.name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");
  const createdAt = new Date(Date.now() - seed.daysAgo * 86400000).toISOString();
  return {
    id,
    slug,
    sku: `VX-${id.toUpperCase()}`,
    name: seed.name,
    brandId: seed.brandId,
    categoryId: seed.categoryId,
    images: [1, 2, 3, 4].map((i) => img(seed.imgSeed, i)),
    thumbnail: img(seed.imgSeed, 1),
    price: seed.price,
    compareAtPrice: seed.compareAtPrice,
    currency: "USD",
    rating: seed.rating,
    reviewCount: seed.reviewCount,
    stock: seed.stock,
    badges: seed.badges,
    shortDescription: seed.shortDescription,
    description: seed.description,
    variants: seed.variants,
    specGroups: seed.specGroups,
    tags: seed.tags,
    createdAt,
    featured: seed.badges.includes("exclusive") || seed.rating >= 4.7,
    bestSeller: seed.badges.includes("bestseller"),
    freeShipping: seed.badges.includes("free-shipping") || seed.price > 200,
    warrantyMonths: seed.warrantyMonths ?? 12,
    colorSwatches: seed.variants.find((v) => v.name === "Color")?.options.map((o) => o.swatch ?? "#111827"),
  };
}

function colorGroup(colors: { label: string; hex: string; inStock?: boolean }[]): ProductVariantGroup {
  return {
    id: "color",
    name: "Color",
    options: colors.map((c) => ({
      id: c.label.toLowerCase().replace(/\s+/g, "-"),
      label: c.label,
      value: c.label,
      swatch: c.hex,
      inStock: c.inStock ?? true,
    })),
  };
}

function storageGroup(sizes: string[]): ProductVariantGroup {
  return {
    id: "storage",
    name: "Storage",
    options: sizes.map((s, i) => ({
      id: s,
      label: s,
      value: s,
      priceDelta: i * 100,
      inStock: true,
    })),
  };
}

